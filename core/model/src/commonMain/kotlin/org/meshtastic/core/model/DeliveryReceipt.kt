package org.meshtastic.core.model

import kotlinx.serialization.Serializable

/**
 * One ack that settled an outgoing packet, kept so the delivery dialog can show who carried it and how well we heard
 * them.
 *
 * Two kinds of ack arrive. An implicit ack is generated by our own radio when it overhears a node rebroadcast our
 * packet: since firmware 2.8.0 it carries that relayer's id byte and the RSSI/SNR we heard the rebroadcast at. An
 * explicit ack comes back over the air from the addressed node of a direct message, and carries the last hop's id byte,
 * the signal of that last hop and the hop count of the way back.
 *
 * Only the relayer's last id byte travels, so the relaying node is resolved by suffix and may be ambiguous.
 */
@Serializable
data class DeliveryReceipt(
    /** Last byte of the relaying node's number, or null when the ack named none. */
    val relayNode: Int? = null,
    /** RSSI in dBm, or null when the radio reported none (firmware before 2.8.0 for implicit acks). */
    val rssi: Int? = null,
    /** SNR in dB, or null when the radio reported none. */
    val snr: Float? = null,
    /** Hops the ack itself travelled, or -1 when unknown. Meaningful only for [fromRecipient] acks. */
    val hopsAway: Int = -1,
    /** True when this ack came from the addressed node of a direct message, not an overheard rebroadcast. */
    val fromRecipient: Boolean = false,
    val viaMqtt: Boolean = false,
    /** Local epoch millis when the ack reached the app. */
    val receivedTime: Long = 0L,
) {
    companion object {
        /** Bounds the list stored per packet; in practice firmware produces one implicit ack plus one explicit ack. */
        const val MAX_PER_PACKET: Int = 16
    }
}

/** Appends [receipt], dropping the oldest entries past [DeliveryReceipt.MAX_PER_PACKET]. */
fun List<DeliveryReceipt>.plusBounded(receipt: DeliveryReceipt): List<DeliveryReceipt> =
    (this + receipt).takeLast(DeliveryReceipt.MAX_PER_PACKET)
